export function errorText(code: string, language: Language) {
  const t = dictionaries[language];
  const map: Record<string, string> = {
    INVALID_SEARCH: t.invalid,
    NETWORK_ERROR: t.network,
    PRODUCTS_UNAVAILABLE: t.provider,
    PRODUCTS_TIMEOUT: t.timeout,
    TOO_MANY_SEARCHES: t.rate,
    HISTORY_NOT_SAVED: t.historyWarning,
    HISTORY_LOAD_FAILED: t.historyError,
    BILLING_UNAVAILABLE: t.billingError,
    SUBSCRIPTION_EXISTS: t.exists,
    SUBSCRIPTION_PENDING: t.pending,
    CANCEL_ERROR: t.cancelError,
  };
  return map[code] ?? t.error;
}
